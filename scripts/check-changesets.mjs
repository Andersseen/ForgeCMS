#!/usr/bin/env node
// The "Changeset required" CI check (spec 092/093). Normally `changeset status --since=origin/main`. When that
// fails inside Changesets prerelease mode because this very pull request also contains the prerelease version
// commit (which consumes its own changesets), accept it iff every changeset the PR added is recorded in pre.json.
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import {
  PUBLIC_FAMILY,
  changesetsCoveredByPrerelease,
  isStablePromotion
} from './release-decision.mjs';

const base = process.argv[2] ?? 'origin/main';
const status = spawnSync('pnpm', ['changeset', 'status', `--since=${base}`], { stdio: 'inherit' });
if (status.status === 0) process.exit(0);

// Stable release-promotion PRs are generated by `changeset pre exit` + `changeset version`.
// They consume the candidate changesets and remove pre.json, so the normal status check sees package
// version changes but no pending changeset. Accept only the exact fixed-family rc.2 -> 1.0.0 transition,
// with the generated 1.0.0 changelog in every public package.
const basePre = spawnSync('git', ['show', `${base}:.changeset/pre.json`], { encoding: 'utf8' });
function readPackages(ref) {
  return PUBLIC_FAMILY.map((name) => {
    const directory = name.slice('@forge-cms/'.length);
    const result = spawnSync('git', ['show', `${ref}:packages/${directory}/package.json`], {
      encoding: 'utf8'
    });
    return result.status === 0 ? JSON.parse(result.stdout) : null;
  }).filter(Boolean);
}
const changelogs = PUBLIC_FAMILY.filter((name) => {
  const directory = name.slice('@forge-cms/'.length);
  const result = spawnSync('git', ['show', `HEAD:packages/${directory}/CHANGELOG.md`], {
    encoding: 'utf8'
  });
  return result.status === 0 && /^## 1\.0\.0\s*$/m.test(result.stdout);
});
const promotion =
  basePre.status === 0 &&
  isStablePromotion({
    basePre: JSON.parse(basePre.stdout),
    headPreActive: existsSync('.changeset/pre.json'),
    basePackages: readPackages(base),
    headPackages: readPackages('HEAD'),
    changelogs
  });
if (promotion) {
  console.log('Changeset check passed: exact rc.2 -> 1.0.0 fixed-family promotion.');
  process.exit(0);
}

const pre = existsSync('.changeset/pre.json')
  ? JSON.parse(readFileSync('.changeset/pre.json', 'utf8'))
  : null;
const diff = spawnSync(
  'git',
  ['diff', '--name-only', '--diff-filter=A', `${base}...HEAD`, '--', '.changeset'],
  { encoding: 'utf8' }
);
const added = diff.stdout.split('\n').filter(Boolean);
const verdict = changesetsCoveredByPrerelease({
  added,
  preChangesets: pre ? (pre.changesets ?? []) : null
});
if (verdict.ok) {
  console.log(`Changeset check passed through prerelease mode: ${verdict.reason}.`);
  process.exit(0);
}
console.error(`Changeset check failed: ${verdict.reason}.`);
process.exit(1);
